def banner(s):
    print()
    print("=" * 78)
    print(s)
    print("=" * 78)


def check(label, got, want, note=""):
    ok = (got == want)
    print(f"  [{'PASS' if ok else 'FAIL'}] {label}: got {got}, expected {want}"
          + (f"   {note}" if note else ""))
    return ok


def main():
    all_ok = True

    # ========================================================================
    banner("PART A -- Example 2 (p.18-20): the ring A and the components")
    # ========================================================================
    F9 = gf.GF(3, 2, [2, 2, 1])           # omega^2 + 2*omega + 2 = 0  (p.18)
    w = F9.from_digits([0, 1])            # omega
    print(f"  F_9 = F_3(w), w^2 + 2w + 2 = 0;  w^2 = {F9.mul(w, w)}"
          f" = {F9.digits(F9.mul(w, w))} digits")
    t1 = [w, 1, 1]                        # x^2 + x + w        (p.18)
    t2 = [2, F9.pow(w, 5), 1]             # x^2 + w^5 x + 2    (p.18)
    irr1 = irreducible_bruteforce(F9, t1)
    irr2 = irreducible_bruteforce(F9, t2)
    print(f"  t1 = x^2 + x + w      : root in F_9? no -> irreducible = {irr1}")
    print(f"  t2 = x^2 + w^5 x + 2  : root in F_9? no -> irreducible = {irr2}")
    all_ok &= check("t1 irreducible over F_9", irr1, True)
    all_ok &= check("t2 irreducible over F_9", irr2, True)

    A2 = AffineAlgebra(F9, t1, t2)
    all_ok &= check("dim_{F_9} A = deg t1 * deg t2", A2.dim, 4)

    idem = A2.find_idempotents()
    prim = idempotent_components(A2, idem)
    one = A2.const(1)
    print(f"  idempotents found: {len(idem)}  (primitive: {len(prim)})")
    all_ok &= check("number of primitive idempotents = N", len(prim), 2)
    if len(prim) == 2:
        d_e1 = A2.span_dim([A2.mul(prim[0], {b: 1}) for b in A2.basis])
        d_e2 = A2.span_dim([A2.mul(prim[1], {b: 1}) for b in A2.basis])
        print(f"  dim_F9(e1 A) = {d_e1},  dim_F9(e2 A) = {d_e2}")
        all_ok &= check("each component is F_81  (dim 2 over F_9)", (d_e1, d_e2), (2, 2))
        all_ok &= check("sum of component dims = dim A", d_e1 + d_e2, 4)

    # Gray map image size
    q, N = 9, 2
    sizeA = q ** A2.dim
    print(f"  |A| = {q}^{A2.dim} = {sizeA};  |F_q^N| = {q}^{N} = {q**N}")
    all_ok &= check("psi: A -> F_q^N can be bijective?", sizeA <= q ** N, False,
                    "|A| exceeds |F_q^N|")

    # ---- the actual A-module C -------------------------------------------
    n = 7
    g1 = [2, F9.pow(w, 5), F9.pow(w, 3), 1]           # x^3 + w^3 x^2 + w^5 x + 2
    g2 = [F9.mul(w, w), 1]                            # x + w^2
    all_ok &= check("g1 | x^7 - 1",
                    gf.pdivmod(F9, [F9.neg(1)] + [0]*6 + [1], g1)[1] in ([0], []), True)
    all_ok &= check("g2 | x^7 - w^2",
                    gf.pdivmod(F9, [F9.neg(F9.mul(w, w))] + [0]*6 + [1], g2)[1] in ([0], []), True)
    pairings = {
        "paper (g1 with lam=1)": [(g1, 1), (g2, F9.mul(w, w))],
        "swapped (g1 with lam=w^2)": [(g2, 1), (g1, F9.mul(w, w))],
    }
    results = {k: module_dim_pairing(A2, prim, v, n) for k, v in pairings.items()}
    print(f"  dim_F9(<g>) by pairing: {results}")
    dimC = results["paper (g1 with lam=1)"]
    print(f"  A-module C = <g>, g = e1 g1 + e2 g2, n = {n}")
    print(f"    deg g1 = {len(g1)-1}, deg g2 = {len(g2)-1}")
    print(f"    dim_F9(C) computed over A            = {dimC}")
    print(f"    sum_S (n - deg g_S)  (paper's k)     = "
          f"{(n-(len(g1)-1)) + (n-(len(g2)-1))}")
    all_ok &= check("dim_F9(C) equals the weighted sum", dimC,
                    2 * (n - (len(g1) - 1)) + 2 * (n - (len(g2) - 1)))
    all_ok &= check("dim_F9(C) <= length of psi(C) = n*N", dimC <= n * N, False,
                    f"dim {dimC} > {n*N}: psi cannot be injective on C")
    all_ok &= check("paper's k for [14,k,4]_9", (n - (len(g1) - 1)) + (n - (len(g2) - 1)), 10)

    # ========================================================================
    banner("PART B -- Example 3 (p.20-21)")
    # ========================================================================
    F25 = gf.GF(5, 2, [2, 4, 1])          # omega^2 + 4 omega + 2 = 0   (p.20)
    w = F25.from_digits([0, 1])
    print(f"  F_25 = F_5(w), w^2 + 4w + 2 = 0;  w^2 = {F25.digits(F25.mul(w, w))}")
    t1 = [F25.pow(w, 13), 1, 1]           # x^2 + x + w^13
    t2 = [1, F25.pow(w, 3), 1]            # x^2 + w^3 x + 1
    irr1 = irreducible_bruteforce(F25, t1)
    irr2 = irreducible_bruteforce(F25, t2)
    print(f"  t1 = x^2 + x + w^13 : irreducible over F_25 = {irr1}")
    print(f"  t2 = x^2 + w^3 x + 1: has root in F_25 = {not irr2}")
    all_ok &= check("t1 irreducible over F_25", irr1, True)
    all_ok &= check("t2 split over F_25", irr2, False)

    A3 = AffineAlgebra(F25, t1, t2)
    all_ok &= check("dim_{F_25} A", A3.dim, 4)
    idem = A3.find_idempotents()
    one = A3.const(1)
    prim = idempotent_components(A3, idem)
    print(f"  idempotents: {len(idem)}, primitive: {len(prim)}")
    all_ok &= check("N = #primitive idempotents", len(prim), 2)
    if len(prim) == 2:
        d_e1 = A3.span_dim([A3.mul(prim[0], {b: 1}) for b in A3.basis])
        d_e2 = A3.span_dim([A3.mul(prim[1], {b: 1}) for b in A3.basis])
        print(f"  dim_F25(e1 A) = {d_e1}, dim_F25(e2 A) = {d_e2}")
        all_ok &= check("components are F_625", (d_e1, d_e2), (2, 2))

        q, N = 25, 2
        all_ok &= check("psi: A -> F_q^N bijective?", q ** A3.dim <= q ** N, False)

        n = 13
        # g1 = (x+4)(x^2 + w x + 1) ;  g2 = x + w^20
        a = [4, 1]
        b = [1, w, 1]
        g1 = [0] * (len(a) + len(b) - 1)
        for i, ai in enumerate(a):
            for j, bj in enumerate(b):
                g1[i + j] = F25.add(g1[i + j], F25.mul(ai, bj))
        g2 = [F25.pow(w, 20), 1]
        print(f"  g1 coefficients {g1}  (Table 1 prints 4, w^5, w^17, 1)")
        all_ok &= check("g1 | x^13 - 1", gf.pdivmod(F25, [F25.neg(1)] + [0]*12 + [1], g1)[1] in ([0], []), True)
        all_ok &= check("g2 | x^13 - w^8",
                        gf.pdivmod(F25, [F25.neg(F25.pow(w, 8))] + [0]*12 + [1], g2)[1] in ([0], []), True)

        # The paper pairs g1 with lambda=1 and g2 with lambda=w^8.  The two
        # primitive idempotents are only determined up to order, so try both.
        pairings = {
            "paper (g1 with lam=1)": [(g1, 1), (g2, F25.pow(w, 8))],
            "swapped": [(g2, 1), (g1, F25.pow(w, 8))],
        }
        results = {k: module_dim_pairing(A3, prim, v, n) for k, v in pairings.items()}
        print(f"  dim_F25(<g>) by pairing: {results}")
        best = results["paper (g1 with lam=1)"]
        all_ok &= check("dim_F25(C) = sum_S 2*(n-deg g_S)", best,
                        2 * (n - (len(g1) - 1)) + 2 * (n - (len(g2) - 1)))
        all_ok &= check("dim_F25(C) <= n*N", best <= n * N, False,
                        f"dim {best} > {n*N}")

    # ========================================================================
    banner("PART C -- the q = 4 ring of Table 1 (p.21)")
    # ========================================================================
    F4 = gf.GF(2, 2, [1, 1, 1])           # omega^2 + omega + 1 = 0
    w = F4.from_digits([0, 1])
    t1 = [w, 1, 1]                        # x^2 + x + w
    t2 = [w, w, 1]                        # x^2 + w x + w
    irr1 = irreducible_bruteforce(F4, t1)
    irr2 = irreducible_bruteforce(F4, t2)
    print(f"  t1 = x^2 + x + w    : irreducible over F_4 = {irr1}")
    print(f"  t2 = x^2 + w x + w  : irreducible over F_4 = {irr2}")
    all_ok &= check("t1 irreducible over F_4", irr1, True)
    all_ok &= check("t2 irreducible over F_4", irr2, True)
    A4 = AffineAlgebra(F4, t1, t2)
    all_ok &= check("dim_{F_4} A", A4.dim, 4)
    all_ok &= check("psi: A -> F_4^2 bijective?", 4 ** A4.dim <= 4 ** 2, False)

    # ========================================================================
    banner("PART D -- Corollary 3.5(2) at e' = 0 (boundary case, audit F3)")
    # ========================================================================
    # p.14: "n = n' p^{e'}, e' a non-negative integer"; Cor 3.5(2) presumes
    # p = 2, e even, ord(lambda) n' | (2^e - 1), and claims |D_{e/2}| = N n/2 + 1.
    # p.14 also asserts D_k(n,q,lambda) is a subset of {0,1,...,floor(n/2)}.
    # Take p = 2, e = 2 (q = 4), n = n' = 3, e' = 0, lambda = 1 (ord = 1).
    #   1 * 3 | (2^2 - 1) = 3   -> hypothesis holds
    #   claimed |D| = N*n/2 + 1 = 2*3/2 + 1 = 4
    #   but D subset of {0,1} so |D| <= 2
    n, N = 3, 2
    bound = n // 2
    claimed = N * n // 2 + 1
    print(f"  q=4, n={n} (=n' with e'=0), lambda=1, k=e/2=1")
    print(f"  hypothesis ord(lambda)*n' | (2^e-1):  1*3 | 3  -> True")
    print(f"  claimed |D| = N*n/2 + 1 = {claimed}")
    print(f"  but D is contained in {{0,...,{bound}}} by p.14, so |D| <= {bound+1}")
    all_ok &= check("claimed count is attainable", claimed <= bound + 1, False)
    all_ok &= check("N*n/2 is an integer for n odd, N=2", (N * n) % 2, 0,
                    "(it is not, for odd N)")

    # ========================================================================
    banner("PART F -- the code the paper actually reports (F_q-component model)")
    # ========================================================================
    # Rebuild the reported [14,10,d] and [26,22,d] as the M-mixed direct sums of
    # the F_q-codes generated by g1 and g2, i.e. exactly the object whose
    # dimension is sum_S (n - deg g_S).  This checks the paper's arithmetic while
    # NOT claiming that this object is the Gray image of the A-module.
    w9 = F9.from_digits([0, 1])
    g1_9 = [2, F9.pow(w9, 5), F9.pow(w9, 3), 1]
    g2_9 = [F9.mul(w9, w9), 1]
    print("  Example 2:  M = [[w, w^3], [w^7, w^5]] on F_9")
    M9 = [[w9, F9.pow(w9, 3)], [F9.pow(w9, 7), F9.pow(w9, 5)]]
    blocks = [fq_code_rows(F9, 7, 1, g1_9), fq_code_rows(F9, 7, F9.mul(w9, w9), g2_9)]
    rowsF = mix_with_M(F9, blocks, M9, 7)
    kF, _ = gf.span_rank(F9, rowsF, 14)
    dualF = gf.nullspace(F9, gf.span_rank(F9, rowsF, 14)[1], 14)
    dF = None
    for wt in range(1, 15):
        found = False
        for Sset in combinations(range(14), wt):
            sub = [[dualF[r][j] for j in Sset] for r in range(len(dualF))]
            if gf.span_rank(F9, sub, wt)[0] < wt:
                found = True
                break
        if found:
            dF = wt
            break
    print(f"    dim = {kF}, d = {dF}   (paper: [14,10,4]_9)")
    all_ok &= check("F_9 model dimension", kF, 10)
    all_ok &= check("F_9 model minimum distance", dF, 4)

    w25 = F25.from_digits([0, 1])
    a25 = [4, 1]
    b25 = [1, w25, 1]
    g1_25 = [0] * 4
    for i, ai in enumerate(a25):
        for j, bj in enumerate(b25):
            g1_25[i + j] = F25.add(g1_25[i + j], F25.mul(ai, bj))
    g2_25 = [F25.pow(w25, 20), 1]
    print("  Example 3:  M = [[w, w^2], [2, w^13]] on F_25")
    M25 = [[w25, F25.mul(w25, w25)], [2, F25.pow(w25, 13)]]
    blocks = [fq_code_rows(F25, 13, 1, g1_25), fq_code_rows(F25, 13, F25.pow(w25, 8), g2_25)]
    rowsF = mix_with_M(F25, blocks, M25, 13)
    kF = gf.span_rank(F25, rowsF, 26)[0]
    print(f"    dim = {kF}   (paper: [26,22,4]_25)")
    all_ok &= check("F_25 model dimension", kF, 22)

