def a_mul_poly(A, f, g):
    """Multiply two polynomials with coefficients in A (lists, low degree first)."""
    out = [dict() for _ in range(len(f) + len(g) - 1)]
    for i, fi in enumerate(f):
        if not fi:
            continue
        for j, gj in enumerate(g):
            if not gj:
                continue
            p = A.mul(fi, gj)
            out[i + j] = A.add(out[i + j], p)
    return out


def a_constacyclic_module(A, n, lam, g):
    """A-submodule of A[x]/<x^n - lam> generated by g.

    The module is the F_q-span of { b_j * x^i * g : 0 <= i < n, b_j a basis of A },
    i.e. n*dim(A) generators.  Returns (dim_{F_q}, rows).
    """
    shifts = []
    cur = list(g) + [dict() for _ in range(n - len(g))]
    for i in range(n):
        shifts.append(cur)
        nxt = [dict() for _ in range(n)]
        for d, c in enumerate(cur):
            if not c:
                continue
            if d + 1 < n:
                nxt[d + 1] = A.add(nxt[d + 1], c)
            else:
                nxt[0] = A.add(nxt[0], A.mul(lam, c))
        cur = nxt
    rows = []
    for poly in shifts:
        for b in A.basis:
            scalar = {b: 1}
            row = []
            for d in range(n):
                row += A.coords(A.mul(scalar, poly[d]))
            rows.append(row)
    return gf.span_rank(A.F, rows, A.dim * n)[0], rows


def fq_cyclic_dim(F, n, lam, g):
    """F_q-dimension of the constacyclic F_q-code generated by g."""
    k = n - (len(g) - 1)
    return k



def idempotent_components(A, idem):
    """Return the list of primitive idempotents, sorted deterministically."""
    one = A.const(1)
    prim = [e for e in idem if e and e != one]
    prim.sort(key=lambda e: tuple(A.coords(e)))
    return prim


def module_dim_pairing(A, prim, pairing, n):
    """dim_{F_q} of <g> where prim[i] carries (poly, lambda-value) = pairing[i]."""
    polys = [pairing[i][0] for i in range(len(prim))]
    maxdeg = max(len(p) for p in polys)
    g = []
    for d in range(maxdeg):
        acc = {}
        for i, poly in enumerate(polys):
            if d < len(poly):
                acc = A.add(acc, A.scalar(poly[d], prim[i]))
        g.append(acc)
    lam = {}
    for i in range(len(prim)):
        lam = A.add(lam, A.scalar(pairing[i][1], prim[i]))
    return a_constacyclic_module(A, n, lam, g)[0]


def fq_code_rows(F, n, lam, g):
    """F_q-basis of the constacyclic F_q-code generated by g (low degree first)."""
    k = n - (len(g) - 1)
    rows = []
    for i in range(k):
        f = [0] * i + list(g)
        while len(f) - 1 >= n:
            c = f[-1]
            f = f[:-1]
            f[0] = F.add(f[0], F.mul(c, lam))
        rows.append([f[j] if j < len(f) else 0 for j in range(n)])
    return rows


def mix_with_M(F, blocks, M, n):
    """Stack the blocks through the N x N matrix M, producing length n*N rows."""
    N = len(M)
    rows = []
    for j, block in enumerate(blocks):
        for h in block:
            vec = []
            for i in range(n):
                vec += [F.mul(h[i], M[j][r]) for r in range(N)]
            rows.append(vec)
    return rows

# ----------------------------------------------------------------------------
# Irreducibility by direct root search (independent of gf.is_irreducible)
# ----------------------------------------------------------------------------


def has_root_in(F, t):
    for a in range(F.q):
        v = 0
        for c in reversed(t):
            v = F.add(F.mul(v, a), c)
        if v == 0:
            return True, a
    return False, None


def irreducible_bruteforce(F, t):
    """True iff t has no root in F.  Valid for deg(t) <= 3 and prime deg."""
    d = len(t) - 1
    if d == 1:
        return False
    r, _ = has_root_in(F, t)
    return not r


