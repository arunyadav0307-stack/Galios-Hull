# ----------------------------------------------------------------------------
# A tiny utility: dense bivariate polynomials over a GF instance.
# Representation: dict {(i,j): coeff}, i = exponent of x1, j = exponent of x2.
# ----------------------------------------------------------------------------


def bv_mul(F, a, b):
    out = {}
    for (i, j), c in a.items():
        for (k, l), d in b.items():
            key = (i + k, j + l)
            out[key] = F.add(out.get(key, 0), F.mul(c, d))
    return {k: v for k, v in out.items() if v}


def bv_add(F, a, b):
    out = dict(a)
    for k, v in b.items():
        out[k] = F.add(out.get(k, 0), v)
    return {k: v for k, v in out.items() if v}


def bv_scale(F, c, a):
    return {k: F.mul(c, v) for k, v in a.items() if F.mul(c, v)}


def reduce_var(F, poly, var, t):
    """Reduce exponents in `var` (0 -> x1, 1 -> x2) modulo the monic poly t."""
    d = len(t) - 1
    out = {}
    for key, c in poly.items():
        e = list(key)
        while e[var] >= d:
            shift = e[var] - d
            e[var] = 0
            # x^d = -(t[0] + t[1] x + ... + t[d-1] x^(d-1))
            for k in range(d):
                nk = list(e)
                nk[var] = k + shift
                kk = tuple(nk)
                out[kk] = F.sub(out.get(kk, 0), F.mul(c, t[k]))
            c = 0
            break
        if c:
            kk = tuple(e)
            out[kk] = F.add(out.get(kk, 0), c)
    # a term with exponent >= d was re-expanded and pushed; iterate until stable
    if any(k[var] >= d for k in out):
        return reduce_var(F, {k: v for k, v in out.items() if v}, var, t)
    return {k: v for k, v in out.items() if v}


class AffineAlgebra:
    """A = F_q[x1,x2] / <t1(x1), t2(x2)>, t_i monic (not necessarily squarefree)."""

    def __init__(self, F, t1, t2):
        self.F = F
        self.t1 = t1
        self.t2 = t2
        self.d1 = len(t1) - 1
        self.d2 = len(t2) - 1
        self.dim = self.d1 * self.d2          # F_q-dimension of A
        self.basis = [(i, j) for i in range(self.d1) for j in range(self.d2)]

    def one(self):
        return {(0, 0): 1}

    def var(self, which):
        return {(1, 0): 1} if which == 0 else {(0, 1): 1}

    def reduce(self, poly):
        p = reduce_var(self.F, poly, 0, self.t1)
        p = reduce_var(self.F, p, 1, self.t2)
        return p

    def mul(self, a, b):
        return self.reduce(bv_mul(self.F, a, b))

    def add(self, a, b):
        return {k: v for k, v in bv_add(self.F, a, b).items() if v}

    def scalar(self, c, a):
        return {k: v for k, v in bv_scale(self.F, c, a).items() if v}

    def const(self, c):
        return {} if c == 0 else {(0, 0): c}

    def coords(self, a):
        return [a.get(b, 0) for b in self.basis]

    def from_coords(self, v):
        return {self.basis[i]: v[i] for i in range(len(v)) if v[i]}

    def is_idempotent(self, e):
        return self.mul(e, e) == e

    def find_idempotents(self):
        """All idempotents, by solving e^2 = e on the monomial basis.

        Uses the structure constants so the inner loop is pure integer work.
        """
        F = self.F
        n = len(self.basis)
        # structure constants: b_i b_j = sum_k mu[i][j][k] b_k
        mu = [[[0] * n for _ in range(n)] for _ in range(n)]
        for i, bi in enumerate(self.basis):
            for j, bj in enumerate(self.basis):
                p = self.mul({bi: 1}, {bj: 1})
                for k, bk in enumerate(self.basis):
                    mu[i][j][k] = p.get(bk, 0)
        found = []
        for cand in product(range(F.q), repeat=n):
            ok = True
            for k in range(n):
                s = 0
                for i in range(n):
                    ci = cand[i]
                    if ci == 0:
                        continue
                    for j in range(n):
                        cj = cand[j]
                        if cj == 0:
                            continue
                        s = F.add(s, F.mul(F.mul(ci, cj), mu[i][j][k]))
                if s != cand[k]:
                    ok = False
                    break
            if ok:
                found.append(cand)
        return [self.from_coords(c) for c in found]

    def span_dim(self, elems):
        rows = [self.coords(e) for e in elems]
        return gf.span_rank(self.F, rows, self.dim)[0]


