def _divides(F, g, f):
    r = gf.pmod(F, f, g) if hasattr(gf, "pmod") else None
    # long division
    f = list(f)
    while len(f) >= len(g) and not (len(f) == 1 and f[0] == 0):
        c = F.mul(f[-1], F.inv(g[-1]))
        d = len(f) - len(g)
        for i in range(len(g)):
            f[d + i] = F.sub(f[d + i], F.mul(c, g[i]))
        f = gf.ptrim(f)
        if len(f) < len(g):
            break
    return len(f) == 1 and f[0] == 0


def _gcd(a, b):
    while b:
        a, b = b, a % b
    return a




