def ring_basis_mul(F, q, t1, t2):
    """multiply two elements of A = F_q[x1,x2]/<t1(x1),t2(x2)>, represented as
    coefficient matrices c[i][j] of x1^i x2^j"""
    d1, d2 = len(t1) - 1, len(t2) - 1

    def flat(M):
        return [M[i][j] for i in range(d1) for j in range(d2)]

    def unflat(v):
        return [[v[i * d2 + j] for j in range(d2)] for i in range(d1)]

    def mul(A, B):
        C = [[0] * (2 * d2 - 1) for _ in range(2 * d1 - 1)]
        for i in range(d1):
            for j in range(d2):
                if not A[i][j]:
                    continue
                for k in range(d1):
                    for l in range(d2):
                        if B[k][l]:
                            C[i + k][j + l] = F.add(C[i + k][j + l],
                                                    F.mul(A[i][j], B[k][l]))
        # reduce x1 powers
        C = reduce_dim(F, C, t1, 0)
        C = reduce_dim(F, C, t2, 1)
        return C
    return flat, unflat, mul, d1, d2


def reduce_dim(F, C, t, axis):
    d = len(t) - 1
    C = [row[:] for row in C]
    if axis == 0:
        for i in range(len(C) - 1, d - 1, -1):
            if any(C[i]):
                for j in range(len(C[i])):
                    if C[i][j]:
                        c = C[i][j]
                        for k in range(d):
                            C[i - d + k][j] = F.add(C[i - d + k][j],
                                                     F.neg(F.mul(c, t[k])))
                C[i] = [0] * len(C[i])
        return C[:d]
    else:
        for i in range(len(C)):
            for j in range(len(C[i]) - 1, d - 1, -1):
                if C[i][j]:
                    c = C[i][j]
                    for k in range(d):
                        C[i][j - d + k] = F.add(C[i][j - d + k],
                                                 F.neg(F.mul(c, t[k])))
                    C[i][j] = 0
            C[i] = C[i][:d]
        return C


def count_idempotents(F, q, t1, t2):
    flat, unflat, mul, d1, d2 = ring_basis_mul(F, q, t1, t2)
    dim = d1 * d2
    idem = []
    for code in range(q ** dim):
        v = []
        x = code
        for _ in range(dim):
            v.append(x % q)
            x //= q
        M = unflat(v)
        M2 = mul(M, M)
        if flat(M2) == v:
            idem.append(v)
    return idem, flat, unflat, mul, dim


def module_dim(F, q, t1, t2, n, lam1, lam2, g1, g2):
    """dim_{F_q} of the ideal generated by g = e1 g1 + e2 g2 in A[x]/(x^n - lam).

    The ideal is spanned over A by {x^i g : i = 0..n-1}; over F_q by
    {b * x^i g : b in an F_q-basis of A}.  We compute the rank of those vectors.
    """
    flat, unflat, mul, d1, d2 = ring_basis_mul(F, q, t1, t2)
    dim = d1 * d2
    idem, _, _, _, _ = count_idempotents(F, q, t1, t2)
    prim = [e for e in idem if e != [0] * dim and _is_primitive(F, e, idem, dim)]
    assert len(prim) == 2, f"expected 2 primitive idempotents, got {len(prim)}"
    e1, e2 = unflat(prim[0]), unflat(prim[1])
    lamM = _axpy(F, lam1, e1, lam2, e2, d1, d2)
    # g as a length-n vector over A
    gvec = []
    for i in range(n):
        c1 = g1[i] if i < len(g1) else 0
        c2 = g2[i] if i < len(g2) else 0
        gvec.append(_axpy(F, c1, e1, c2, e2, d1, d2))

    def shift(v):
        return [mul(lamM, v[-1])] + [x[:] for x in v[:-1]]

    basis = [unflat(v) for v in [[1 if k == j else 0 for k in range(dim)]
                                 for j in range(dim)]]
    rows = []
    v = [x[:] for x in gvec]
    for _ in range(n):
        for b in basis:
            rows.append([x for el in [mul(b, w) for w in v] for x in flat(el)])
        v = shift(v)
    rk, _ = gf.span_rank(F, rows, n * dim)
    return rk, len(prim)


def _axpy(F, c1, M1, c2, M2, d1, d2):
    return [[F.add(F.mul(c1, M1[i][j]), F.mul(c2, M2[i][j]))
             for j in range(d2)] for i in range(d1)]


def _is_primitive(F, e, idem, dim):
    # e is primitive if it is not the sum of two nonzero orthogonal idempotents
    for f in idem:
        if f == e or f == [0] * dim:
            continue
        g = [F.sub(e[i], f[i]) for i in range(dim)]
        if g in idem and any(g):
            return False
    return True


